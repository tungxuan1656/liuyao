import assert from 'node:assert/strict';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const tasksDirectory = join(dirname(fileURLToPath(import.meta.url)), '../tasks');
const indexPath = join(tasksDirectory, 'index.md');

function parseTask(file, text) {
  const header = text.split(/^## /m)[0];
  const title = header.match(/^# (.+?) - (.+)\r?$/m);
  assert(title, `${file}: expected '# ID - Title'`);
  const field = name => {
    const matches = [...header.matchAll(new RegExp(`^- ${name}: (.+)\\r?$`, 'gm'))];
    assert.equal(matches.length, 1, `${file}: expected one ${name} field`);
    const value = matches[0][1].trim();
    assert(value, `${file}: expected non-empty ${name} field`);
    return value;
  };
  const status = field('Status');
  assert(
    ['todo', 'active', 'blocked', 'done'].includes(status),
    `${file}: invalid status ${status}`,
  );
  const start = field('Required to start');
  const dependencies = [...start.matchAll(/\[[^\]]+\]\(([^)]+)\)/g)].map(match =>
    match[1].replace(/^\.\//, ''),
  );
  const remainingGate = start.replace(/\[[^\]]+\]\([^)]+\)/g, '').replace(/[,;\s]/g, '');
  const manualGate = !/^none\.?$/i.test(start) && (!dependencies.length || Boolean(remainingGate));
  // Historical snapshots below Handoff must not override current blockers.
  const handoff = text.split(/^## Handoff\r?$/m)[1]?.split(/^#{2,3} /m)[0] ?? '';
  const blockers = [...handoff.replaceAll('**', '').matchAll(/^- Blockers: (.+)\r?$/gm)];
  assert(blockers.length <= 1, `${file}: expected at most one current Blockers field`);
  const blocker = blockers[0]?.[1].trim();
  const blockerState =
    !blocker || /^(?:not evaluated|unknown|not assessed)\b/i.test(blocker)
      ? 'unreviewed'
      : /^none\.?$/i.test(blocker)
        ? 'none'
        : 'blocked';
  return {
    file,
    id: title[1].trim(),
    title: title[2].trim(),
    status,
    start,
    dependencies,
    manualGate,
    blockerState,
  };
}

function readiness(task, byFile) {
  if (task.status !== 'todo') return '-';
  if (task.dependencies.some(file => byFile.get(file).status !== 'done')) return 'no';
  if (task.manualGate) return 'review start gate';
  if (task.blockerState === 'blocked') return 'no (blocker)';
  return task.blockerState === 'unreviewed' ? 'review blockers' : 'yes';
}

function renderIndex(tasks) {
  const byFile = new Map(tasks.map(task => [task.file, task]));
  assert.equal(new Set(tasks.map(task => task.id)).size, tasks.length, 'Duplicate task IDs');
  for (const task of tasks) {
    for (const dependency of task.dependencies) {
      assert(byFile.has(dependency), `${task.file}: unknown dependency ${dependency}`);
      assert.notEqual(dependency, task.file, `${task.file}: task depends on itself`);
    }
  }
  const visited = new Set();
  const visiting = new Set();
  const visit = file => {
    if (visited.has(file)) return;
    assert(!visiting.has(file), `Dependency cycle: ${[...visiting, file].join(' -> ')}`);
    visiting.add(file);
    for (const dependency of byFile.get(file).dependencies) visit(dependency);
    visiting.delete(file);
    visited.add(file);
  };
  for (const task of tasks) visit(task.file);
  const cell = value => value.replace(/\|/g, '\\|');
  const table = selected =>
    [
      '| Task | Title | Status | Required To Start | Ready |',
      '| --- | --- | --- | --- | --- |',
      ...selected.map(task => {
        const start = task.manualGate
          ? task.start
          : task.dependencies.map(file => byFile.get(file).id).join(', ') || 'none';
        return `| [${cell(task.id)}](${task.file}) | ${cell(task.title)} | ${task.status} | ${cell(start)} | ${readiness(task, byFile)} |`;
      }),
    ].join('\n');
  const candidates = tasks.filter(task =>
    ['yes', 'review blockers'].includes(readiness(task, byFile)),
  );
  return [
    '# Tasks',
    '',
    '<!-- Generated by scripts/task-index.mjs. Do not edit by hand. -->',
    '',
    'Task files are the source of truth. Run `pnpm tasks:index` after changing task membership, status, start gates, or blockers. `pnpm tasks:check` checks freshness without writing files.',
    '',
    '[Knowledge delivery sequence](knowledge-roadmap.md).',
    '',
    '## Ready To Start',
    '',
    'Candidates have `todo` status, completed start dependencies, and no explicit blocker. `yes` means blockers are recorded as `none`; `review blockers` means assessment is missing or not yet performed. Review those blockers before starting. This view grants no approval, assigns no priority, and does not evaluate integration/release gates.',
    '',
    candidates.length ? table(candidates) : 'No start candidates.',
    '',
    '## All Tasks',
    '',
    table(tasks),
    '',
    '## Legacy History',
    '',
    '[Retention and ID mapping](../features/README.md). Do not update the frozen feature index or root progress log.',
    '',
  ].join('\n');
}

function selfCheck() {
  const fixture = (id, status, start = 'none', blockers = 'none.') =>
    parseTask(
      `task-${id}.md`,
      `# ${id} - Example | title\n\n- Status: ${status}\n- Required to start: ${start}\n\n## Handoff\n\n- Blockers: ${blockers}\n\n### Historical snapshot\n\n- Status: blocked\n- Blockers: historical issue\n`,
    );
  const done = fixture('a', 'done');
  const ready = fixture('b', 'todo', '[a](task-a.md)');
  const waiting = fixture('c', 'todo', '[b](task-b.md)');
  const unknown = fixture('d', 'todo', 'none', 'not evaluated until selection.');
  const blocked = fixture('e', 'todo', 'none', 'Awaiting supplied source.');
  const manual = fixture('f', 'todo', 'owner approval');
  const tasks = [done, ready, waiting, unknown, blocked, manual];
  const byFile = new Map(tasks.map(task => [task.file, task]));
  assert.deepEqual(
    tasks.map(task => readiness(task, byFile)),
    ['-', 'yes', 'no', 'review blockers', 'no (blocker)', 'review start gate'],
  );
  const output = renderIndex(tasks);
  const candidates = output.split('## Ready To Start\n')[1].split('## All Tasks')[0];
  assert(candidates.includes('[b](task-b.md)') && candidates.includes('[d](task-d.md)'));
  assert(!candidates.includes('[c](task-c.md)') && !candidates.includes('[e](task-e.md)'));
  assert(output.includes('Example \\| title'));
  assert.throws(
    () => renderIndex([fixture('a', 'todo', '[missing](task-missing.md)')]),
    /unknown dependency/,
  );
  assert.throws(() => renderIndex([fixture('a', 'todo', '[a](task-a.md)')]), /depends on itself/);
  assert.throws(
    () =>
      renderIndex([fixture('a', 'todo', '[b](task-b.md)'), fixture('b', 'todo', '[a](task-a.md)')]),
    /Dependency cycle: task-a\.md -> task-b\.md -> task-a\.md/,
  );
  assert.throws(
    () =>
      renderIndex([
        done,
        fixture('b', 'todo', '[c](task-c.md)'),
        fixture('c', 'active', '[d](task-d.md)'),
        fixture('d', 'blocked', '[b](task-b.md)'),
      ]),
    /Dependency cycle: task-b\.md -> task-c\.md -> task-d\.md -> task-b\.md/,
  );
  assert.doesNotThrow(() =>
    renderIndex([
      done,
      ready,
      fixture('c', 'todo', '[a](task-a.md)'),
      fixture('d', 'todo', '[b](task-b.md), [c](task-c.md)'),
    ]),
  );
  assert.throws(() => renderIndex([done, done]), /Duplicate task IDs/);
  assert.throws(() => fixture('a', 'unknown'), /invalid status/);
  assert.throws(
    () => parseTask('task-a.md', '# a - Example\n- Status: todo\n'),
    /Required to start/,
  );
  assert.equal(readiness(fixture('g', 'blocked'), byFile), '-');
  assert.equal(readiness(fixture('h', 'active'), byFile), '-');
  const missingBlockers = parseTask(
    'task-i.md',
    '# i - Example\n- Status: todo\n- Required to start: none\n',
  );
  assert.equal(readiness(missingBlockers, byFile), 'review blockers');
  const boldBlocker = parseTask(
    'task-j.md',
    '# j - Example\n- Status: todo\n- Required to start: none\n## Handoff\n- **Blockers:** awaiting source\n',
  );
  assert.equal(readiness(boldBlocker, byFile), 'no (blocker)');
  assert.throws(
    () => fixture('k', 'todo', 'none', 'none\n- Blockers: awaiting source'),
    /current Blockers/,
  );
  assert.throws(
    () =>
      parseTask(
        'task-l.md',
        '# l - Example\n- Status: todo\n- Status: done\n- Required to start: none\n',
      ),
    /one Status/,
  );
  assert.equal(
    parseTask('task-m.md', '# m - Example\r\n- Status: todo\r\n- Required to start: none\r\n')
      .title,
    'Example',
  );
  assert.throws(() => fixture('n', 'todo', '  '), /non-empty Required to start/);
  assert.equal(readiness(fixture('o', 'todo', ',;'), byFile), 'review start gate');
  process.stdout.write('PASS task index self-checks\n');
}

async function main() {
  const args = process.argv.slice(2);
  assert(
    args.length <= 1 && args.every(arg => ['--check', '--self-test'].includes(arg)),
    'Usage: node scripts/task-index.mjs [--check|--self-test]',
  );
  if (args[0] === '--self-test') return selfCheck();
  const files = (await readdir(tasksDirectory)).filter(file => /^task-.+\.md$/.test(file)).sort();
  const tasks = await Promise.all(
    files.map(async file => parseTask(file, await readFile(join(tasksDirectory, file), 'utf8'))),
  );
  const expected = await format(renderIndex(tasks), {
    ...(await resolveConfig(indexPath)),
    parser: 'markdown',
  });
  if (args[0] === '--check') {
    assert(
      (await readFile(indexPath, 'utf8')) === expected,
      'Task index is stale. Run pnpm tasks:index.',
    );
    process.stdout.write(`PASS task index freshness (${tasks.length} tasks)\n`);
  } else {
    await writeFile(indexPath, expected);
    process.stdout.write(`Generated tasks/index.md (${tasks.length} tasks)\n`);
  }
}

main().catch(error => {
  process.stderr.write(`${error.message}\n`);
  process.exitCode = 1;
});
